    static func text(_ source: String, locale: String) -> String {
        guard locale == "en-US" else { return source }
        if let translated = english[source] { return translated }
        // Dynamic pairs from AccountSettingsPage, ChannelBindingsPanel and RoleIdentityPanel.
        let templates: [(String, String)] = [
            ("^颜色 (#[0-9a-fA-F]{6})$", "Color $1"),
            ("^共 ([0-9]+) 笔$", "$1 total"), ("^第 ([0-9]+) 页$", "Page $1"),
            ("^有效至 (.+)$", "Valid until $1"), ("^最近活动 · (.+)$", "Last active · $1"),
            ("^([0-9]+) 输入 · ([0-9]+) 输出 token$", "$1 input · $2 output token"),
            ("^(.+) 的 AI 伙伴$", "$1’s AI companion"), ("^平台账号：(.+)$", "Platform account: $1"),
            ("^撤销 (.+) 会话$", "Revoke $1 session"),
            ("^(.+) 将立即退出，未保存的操作可能丢失。$", "$1 will be signed out immediately. Unsaved work may be lost."),
            ("^剩余 ([0-9]+) 分 ([0-9]+) 秒，只可使用一次。不要转发给他人。$", "$1m $2s remaining. Single use only. Do not share it.")
        ]
        for (pattern, replacement) in templates {
            if source.range(of: pattern, options: .regularExpression) != nil { return source.replacingOccurrences(of: pattern, with: replacement, options: .regularExpression) }
        }
        return source
    }
