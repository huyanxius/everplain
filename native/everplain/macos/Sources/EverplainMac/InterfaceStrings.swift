func epLocalized(_ source: String) -> String { EPInterfaceStrings.text(source, locale: UserDefaults.standard.string(forKey: "qunxue.interface-locale") ?? "zh-CN") }

struct EPText: View {
    let source: String
    @AppStorage("qunxue.interface-locale") private var locale = "zh-CN"
    init(_ source: String) { self.source = source }
    var body: some View { Text(EPInterfaceStrings.text(source, locale: locale)) }
}

struct EPButton: View {
    let title: String
    let role: ButtonRole?
    let action: () -> Void
    init(_ title: String, role: ButtonRole? = nil, action: @escaping () -> Void) { self.title = title; self.role = role; self.action = action }
    var body: some View { Button(role: role, action: action) { EPText(title) } }
}

struct EPLink: View {
    let title: String
    let destination: URL
    init(_ title: String, destination: URL) { self.title = title; self.destination = destination }
    var body: some View { Link(destination: destination) { EPText(title) } }
}

struct EPTextField: View {
    let title: String
    @Binding var text: String
    @AppStorage("qunxue.interface-locale") private var locale = "zh-CN"
    init(_ title: String, text: Binding<String>) { self.title = title; _text = text }
    var body: some View { TextField(EPInterfaceStrings.text(title, locale: locale), text: $text) }
}

